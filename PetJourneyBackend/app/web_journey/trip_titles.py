"""行程标题接到方位词后面时的说法。**这个模块不导入任何东西。**

单独成一个模块，是因为 `web_agent/moment.py` 也要用它，而那边的 `MomentBuilder` 明写
「鸭子类型，避免引擎之间直接依赖」——为了一个纯字符串函数把整串交通模块拖进去不值当（I 2026-09-24 裁定）。
口径仍然只有这一处：`web_journey/snapshot.py`、`web_agent/moment.py`、`routers/web/public.py` 都调它。
"""

from __future__ import annotations


def going_to(title: str) -> str:
    """把行程标题变成能接在「去」后面的说法：削掉它开头自带的方位词。

    目录里的标题本身就带方位词，直接拼会重复：
      「在咖啡馆帮工」→「TA 在去**在**咖啡馆帮工的路上」
      「去附近喝一杯」→「TA 在去**去**附近喝一杯的路上」
    后一种是报缺陷时没提到的那一半，而 `local:cafe`（去附近喝一杯）恰恰是最常走的近处目的地——
    **只削「在」会把它漏下**。

    两步削法沿用 `local.py:157,163` 造地点名时早就在用的那条口径，不另起一套。
    只削开头（`removeprefix` 语义）：「自己开车去兜风」里的「去」不动。

    **不要拿它去削地点名**：真实地名里就有以方位词开头的（「在水一方咖啡」），
    在那里削前缀等于改掉一个真实地名（`moment.py:98` 有一条用例专门钉住这件事）。
    """
    return title.removeprefix("在").removeprefix("去")
